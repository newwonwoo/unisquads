const JIP = "집합건물";

// 등기 후보 하나. sojae는 소재지, buldnm은 건물명, unique_no는 고유번호다.
// floor는 등기부의 층 필드 — 실측(진흥아파트)에서 호가 "1"로만 오고 층이
// 이 필드로 갈리는 건물이 있어 함께 옮긴다.
const c = (unique_no, dong, ho, sojae, buldnm, floor = "") =>
  ({ unique_no, dong, ho, sojae, buldnm, floor, real_cls_cd: JIP });

// 층×호로 후보를 펼친다. 등기부는 층과 호를 결합해 "301"처럼 적는다.
function floors(prefix, sojae, buldnm, dong, floorList, roomList) {
  const out = [];
  for (const floor of floorList) {
    for (const room of roomList) {
      const ho = `${floor}${String(room).padStart(2, "0")}`;
      out.push(c(`${prefix}-${dong}-${ho}`, dong, ho, sojae, buldnm, String(floor)));
    }
  }
  return out;
}

